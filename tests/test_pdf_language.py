"""Fase B · PDF en el idioma de la empresa (diccionario central app/services/pdf_i18n).

- Empresa en espanol: ningun texto cambia (regla de oro).
- Ingles/frances: etiquetas, encabezados y pies traducidos; los datos no.
"""
from __future__ import annotations

import base64
import re
import zlib

import pytest

from app.services import company_locale as cl
from app.services import pdf_i18n

ES = {"currency": "COP", "timezone": "America/Bogota", "language": "es"}
EN = {"currency": "USD", "timezone": "America/Chicago", "language": "en"}
FR = {"currency": "EUR", "timezone": "Europe/Paris", "language": "fr"}


def pdf_texts(raw: bytes) -> list[str]:
    chunks = [raw]
    for stream in re.findall(rb"stream\r?\n(.*?)\r?\n?endstream", raw, re.S):
        for decode in (zlib.decompress, lambda b: zlib.decompress(base64.a85decode(b.strip().removesuffix(b"~>")))):
            try:
                chunks.append(decode(stream))
                break
            except Exception:
                pass
    out = []
    for chunk in chunks:
        for m in re.findall(rb"\(((?:[^()\\]|\\.)*)\)\s*Tj", chunk):
            t = re.sub(rb"\\([()\\])", rb"\1", m)
            t = re.sub(rb"\\(\d{3})", lambda x: bytes([int(x.group(1), 8)]), t)
            out.append(t.decode("cp1252", "replace"))
    return out


def in_company(locale, fn, *args):
    tokens = cl.use(locale)
    try:
        return fn(*args)
    finally:
        cl.reset(tokens)


def test_spanish_never_changes_any_text():
    for table in (pdf_i18n.EN, pdf_i18n.FR):
        for key in table:
            assert pdf_i18n.tr(key, "es") == key
            assert pdf_i18n.tr(f"<b>{key}</b> 1", "es") == f"<b>{key}</b> 1"
    assert in_company(ES, pdf_i18n.tr, "Total a pagar") == "Total a pagar"
    assert pdf_i18n.tr("Total a pagar") == "Total a pagar", "sin empresa en curso: espanol"


@pytest.mark.parametrize("text,en,fr", [
    ("Fecha: 2026-10-11", "Date: 2026-10-11", "Date : 2026-10-11"),
    ("<b>Fecha:</b> 2026-10-11", "<b>Date:</b> 2026-10-11", "<b>Date :</b> 2026-10-11"),
    ("Pagina 2", "Page 2", "Page 2"),
    ("Página 1 de 3", "Page 1 of 3", "Page 1 sur 3"),
    ("TOTAL NÓMINA", "PAYROLL TOTAL", "TOTAL PAIE"),
    ("Resumen por empleado (5)", "Summary by employee (5)", "Résumé par employé (5)"),
    ("Planilla de Sanidad · generada por CLONEXA", "Sanitation sheet · generated by CLONEXA", "Fiche sanitaire · générée par CLONEXA"),
    ("Mesa 5", "Table 5", "Table 5"),
])
def test_labels_are_translated(text, en, fr):
    assert pdf_i18n.tr(text, "en") == en
    assert pdf_i18n.tr(text, "fr") == fr


def test_data_and_unknown_text_stay_in_spanish():
    assert pdf_i18n.tr("Instalación de rack", "en") == "Instalación de rack"
    assert pdf_i18n.tr("Horas de la tarde", "en") == "Horas de la tarde", "una etiqueta solo se traduce sola o con un numero"
    assert pdf_i18n.tr(None, "en") is None and pdf_i18n.tr("", "en") == ""


QUOTE = {"id": "q1", "quote_number": "COT-0007", "customer_name": "Cliente", "items": [{"description": "Instalación de rack", "quantity": 2, "unit_price": 150000, "total": 300000}],
         "subtotal": 300000, "discount": 0, "total": 300000, "notes": "Validez 15 días", "created_at": "2026-10-11T15:00:00Z", "status": "sent"}


def test_quote_pdf_in_company_language():
    from app.api.v1.endpoints import mini_panel_quotes as mq

    es = pdf_texts(in_company(ES, mq._build_quote_pdf, QUOTE, {"name": "Velvet"}, "quote"))
    en = pdf_texts(in_company(EN, mq._build_quote_pdf, QUOTE, {"name": "VOLTAGE"}, "quote"))
    assert "COTIZACIÓN" in es and "Datos del cliente" in es and "$ 300.000" in es, "espanol y pesos como siempre"
    assert "QUOTE" in en and "Customer details" in en and "Qty" in en and "$300,000.00" in en
    assert "Instalación de rack" in en, "los conceptos (datos) no se traducen"


def test_report_pdf_in_french_and_spanish_identical_texts():
    from app.api.v1.endpoints import reports

    payload = {"company": {"name": "X"}, "period": {"label": "7d", "start": "2026-10-01", "end": "2026-10-07"}, "kpis": [], "rows": []}
    try:
        es = pdf_texts(in_company(ES, reports.build_report_pdf_bytes, payload, None))
        fr = pdf_texts(in_company(FR, reports.build_report_pdf_bytes, payload, None))
    except Exception as exc:  # el payload minimo no aplica a este constructor
        pytest.skip(f"payload de ejemplo no aplica: {exc}")
    assert "Resumen ejecutivo" in es and "Résumé" in fr
    assert len(es) == len(fr), "mismo PDF, solo cambian los textos"
