def build_report_pdf(board: dict, *, logo: Optional[bytes], now: datetime, leader: Optional[str] = None, lang: str = "es") -> bytes:
    """Carta vertical por operacion: 1) cifras, 2) personal A-Z, 3) notas por persona y fecha, 4) alertas."""
    from reportlab.lib.utils import simpleSplit

    t = texts(lang)
    company = str((board.get("company") or {}).get("name") or "")
    period = board.get("period") or {}
    ops = board.get("operations") or []
    single = ops[0] if len(ops) == 1 else None
    labels = [t["name"], t["days"], t["shift"], t["pause"], t["payable"], t["ot"], t["notes"]]
    widths = [w * INNER for w in (0.34, 0.07, 0.13, 0.12, 0.13, 0.13, 0.08)]
    zone_name = single["tz"] if single else None
    made_at = now.astimezone(us_time.zone(zone_name)) if zone_name else now
    made_label = f"{t['made_at']} {day_short(made_at.date().isoformat(), t)} {made_at:%H:%M} {us_time.abbr(zone_name, now) if zone_name else 'UTC'}"
    title = f"{t['report']} · {single['name'] if single else company}"
    zone_note = t["local"].format(a=single["abbr"]) if single else t["local_each"]
    right = ([f"{t['leader']}: {leader}"] if leader else []) + [t["made_by"], made_label]

    def draw(total: int) -> _Page:
        p = _Page(f"{company} · {single['name'] if single else t['report']} · {t['report']}", t, total)
        p.letterhead(logo, company, title, f"{period_text(period.get('start'), period.get('end'), t)} · {zone_note}", right)
        if not ops:
            p.text(MARGIN, p.y, t["no_people"], 9, color=SOFT)
        for index, op in enumerate(ops):
            accent = ACCENT.get(op.get("color"), NAVY)
            if index:
                p.next_page()
            if not single:
                p.text(MARGIN, p.y, f"{op['name']} ({op['abbr']})" if op.get("abbr") else op["name"], 12, bold=True, color=accent)
                p.y -= 18
            f = op.get("figures") or {}
            p.heading(t["s1"], accent)
            p.tiles([(t["shift"], hm(f.get("connected")), None), (t["pause"], hm(f.get("pause")), None), (t["payable"], hm(f.get("payable")), None),
                     (t["ot"], hm(f.get("overtime")), None), (t["notes"], str(int(f.get("notes") or 0)), None)])
            p.heading(t["s2"], accent)
            p.table_head(labels, widths)
            for i, person in enumerate(op.get("people") or []):
                if p.room(20):
                    p.table_head(labels, widths)
                if i % 2 == 0:
                    p.c.setFillColorRGB(*ZEBRA)
                    p.c.rect(MARGIN, p.y - 5, INNER, 17, stroke=0, fill=1)
                x = MARGIN
                cells = [person.get("name"), person.get("days_worked") or 0, hm(person.get("connected")), hm(person.get("pause")), hm(person.get("payable")), hm(person.get("overtime")), person.get("notes") or 0]
                for value, w in zip(cells, widths):
                    p.text(x + 4, p.y, value, 8.2, maxw=w - 6)
                    x += w
                p.y -= 17
            p.y -= 10
            p.heading(t["s3"], accent)
            groups = notes_by_person(op.get("notes") or [])
            if not groups:
                p.text(MARGIN, p.y, t["no_notes"], 8.5, color=SOFT)
                p.y -= 16
            for name, notes in groups:
                p.room(30)
                p.text(MARGIN, p.y, name, 8.8, bold=True, color=NAVY, maxw=INNER)
                p.y -= 12
                for note in notes:
                    stamp = f"{day_short(note.get('d'), t)} {note.get('t') or ''} {note.get('a') or ''}".strip()
                    lines = simpleSplit(_latin(note.get("text")), "Helvetica", 8.3, INNER - 12) or [""]
                    p.room(12)
                    p.text(MARGIN + 6, p.y, stamp, 7.3, color=SOFT)
                    p.y -= 10
                    for line in lines:
                        p.room(11)
                        p.text(MARGIN + 6, p.y, line, 8.3)
                        p.y -= 10.5
                p.y -= 2
                p.c.setStrokeColorRGB(*LINE)
                p.c.setLineWidth(0.4)
                p.c.setDash(2, 2)
                p.c.line(MARGIN, p.y + 3, WIDTH - MARGIN, p.y + 3)
                p.c.setDash()
                p.y -= 7
            p.y -= 6
            p.heading(t["s4"], accent)
            alerts = op.get("alerts") or []
            if not alerts:
                p.text(MARGIN, p.y, t["no_alerts"], 8.5, color=SOFT)
                p.y -= 16
            for alert in alerts:
                for line in simpleSplit(_latin(alert_line(alert, t)), "Helvetica", 8.3, INNER - 6) or [""]:
                    p.room(12)
                    p.text(MARGIN + 6, p.y, line, 8.3)
                    p.y -= 11
        return p

    return _two_pass(draw)
