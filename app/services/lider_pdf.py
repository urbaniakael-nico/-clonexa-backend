def build_attendance_pdf(crm: dict, *, company: str, leader: str, logo: Optional[bytes], now: datetime, limit_hours: float, lang: str = "es") -> bytes:
    """Carta vertical: membrete, semaforo y tabla A-Z con una linea para firmar cada persona."""
    from reportlab.lib.utils import simpleSplit

    t = texts(lang)
    op = crm["operation"]
    local = now.astimezone(us_time.zone(op["timezone"]))
    abbr = op.get("abbr") or us_time.abbr(op["timezone"], now)
    counts = crm.get("counts") or {}
    widths = [w * INNER for w in (0.05, 0.27, 0.11, 0.17, 0.07, 0.08, 0.08, 0.17)]
    labels = [t["num"], t["name"], t["role"], t["state"], t["origin"], t["in"], t["time"], t["sign"]]

    def draw(total: int) -> _Page:
        p = _Page(f"{company} · {op['name']} · {t['attendance']}", t, total)
        p.letterhead(logo, company, f"{t['attendance']} · {op['name']}", f"{t['connection']} · {day_long(local.date(), t)} · {local:%H:%M} {abbr}",
                     [f"{t['leader']}: {leader}", t["made_by"]])
        p.tiles([(t[k], str(int(counts.get(k) or 0)), STATE_COLOR[k]) for k in STATE_ORDER])
        p.table_head(labels, widths)
        for index, person in enumerate(crm.get("people") or [], 1):
            lines = simpleSplit(_latin(person.get("name")), "Helvetica", 8.5, widths[1] - 8)[:2] or [""]
            height = 26 if len(lines) > 1 else 21
            if p.room(height + 4):
                p.table_head(labels, widths)
            if index % 2:
                p.c.setFillColorRGB(*ZEBRA)
                p.c.rect(MARGIN, p.y - height + 11, INNER, height, stroke=0, fill=1)
            state = person.get("state") or "no_shift"
            x, base = MARGIN, p.y - 1
            p.text(x + 4, base, str(index), 8.5, color=SOFT)
            x += widths[0]
            for i, line in enumerate(lines):
                p.text(x + 4, base - 10 * i, line, 8.5)
            x += widths[1]
            p.text(x + 4, base, person.get("role") or "—", 8, maxw=widths[2] - 6)
            x += widths[2]
            p.c.setFillColorRGB(*STATE_COLOR.get(state, STATE_COLOR["no_shift"]))
            p.c.circle(x + 7, base + 2.8, 3, stroke=0, fill=1)
            p.text(x + 13, base, t.get(state, state), 8, maxw=widths[3] - 15)
            x += widths[3]
            p.text(x + 4, base, t.get(person.get("origin") or "", "—"), 8, maxw=widths[4] - 6)
            x += widths[4]
            p.text(x + 4, base, person.get("since") or "—", 8, maxw=widths[5] - 6)
            x += widths[5]
            minutes = person.get("minutes")
            over = state == "to_confirm" and minutes
            p.text(x + 4, base, f"+{limit_hours:g} h" if over else hm(minutes) if minutes is not None else "—", 8, maxw=widths[6] - 6)
            x += widths[6]
            p.c.setStrokeColorRGB(*SOFT)
            p.c.setLineWidth(0.5)
            p.c.line(x + 4, base - 1, MARGIN + INNER - 4, base - 1)
            p.y -= height
        return p

    return _two_pass(draw)


