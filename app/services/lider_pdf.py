def texts(lang: Any) -> dict:
    return TEXT["en" if lang == "en" else "es"]


def hm(minutes: Any) -> str:
    m = max(0, int(minutes or 0))
    return f"{m // 60} h {m % 60:02d}"


def day_short(iso_day: Optional[str], t: dict) -> str:
    if not iso_day:
        return ""
    d = date.fromisoformat(iso_day)
    return f"{t['wd'][d.weekday()]} {d.day:02d} {t['mo'][d.month - 1]}"


def day_long(day: date, t: dict) -> str:
    return f"{t['wd_long'][day.weekday()]} {day.day:02d} {t['mo'][day.month - 1]} {day.year}"


def period_text(start: Optional[str], end: Optional[str], t: dict) -> str:
    if not start:
        return ""
    if start == end or not end:
        return f"{day_short(start, t)} {date.fromisoformat(start).year}"
    return f"{day_short(start, t)} – {day_short(end, t)} {date.fromisoformat(end).year}"


def notes_by_person(notes: list[dict]) -> list[tuple[str, list[dict]]]:
    """Notas agrupadas por persona (A-Z) y, dentro de cada persona, por fecha y hora."""
    groups: dict[str, list[dict]] = {}
    for note in notes or []:
        groups.setdefault(str(note.get("employee") or ""), []).append(note)
    return [(name, sorted(groups[name], key=lambda n: str(n.get("at") or ""))) for name in sorted(groups, key=reports_board.sort_key)]


def alert_line(alert: dict, t: dict) -> str:
    when = f"{day_short(alert.get('d'), t)} {alert.get('t') or ''} {alert.get('a') or ''}".strip()
    who = f"{alert.get('employee') or ''} · {when}"
    kind = alert.get("kind")
    if kind in ("outside", "no_location"):
        return f"{t[kind]}: {who} ({t['marks'].get(alert.get('mark'), alert.get('mark') or '')})"
    if kind == "to_confirm":
        return f"{t['open'] if alert.get('open') else t['held']} {hm(alert.get('minutes'))}: {who}"
    return f"{t['near']} ({hm(alert.get('minutes'))} {t['week']}): {who}"


async def company_logo(db: Any, company_id: Any) -> Optional[bytes]:
    """El logo de la marca de la empresa. Sin logo, o si falla, el membrete sale con el nombre."""
    from app.services import panel_logo

    try:
        return await panel_logo.panel_logo_bytes(db, company_id)
    except Exception as exc:
        await db.rollback()
        log.warning("Logo del PDF no disponible (%s): %s", company_id, type(exc).__name__)
        return None


class _Page:
    """Un PDF por paginas con membrete en la primera y "Pagina X de Y" en todas."""

    def __init__(self, footer: str, t: dict, total: int):
        from reportlab.pdfgen import canvas

        self.buf = io.BytesIO()
        self.c = canvas.Canvas(self.buf, pagesize=(WIDTH, HEIGHT))
        self.footer_text, self.t, self.total = footer, t, total
        self.page, self.y = 1, HEIGHT - MARGIN

    def fit(self, value: Any, size: float, maxw: float, font: str = "Helvetica") -> str:
        from reportlab.pdfbase.pdfmetrics import stringWidth

        s = _latin(value)
        while s and stringWidth(s, font, size) > maxw:
            s = s[:-2] + "…" if len(s) > 2 else ""
        return s

    def text(self, x: float, y: float, value: Any, size: float = 9, bold: bool = False, color=INK, right: bool = False, maxw: Optional[float] = None) -> None:
        font = "Helvetica-Bold" if bold else "Helvetica"
        self.c.setFont(font, size)
        self.c.setFillColorRGB(*color)
        s = self.fit(value, size, maxw, font) if maxw else _latin(value)
        (self.c.drawRightString if right else self.c.drawString)(x, y, s)

    def footer(self) -> None:
        self.c.setStrokeColorRGB(*LINE)
        self.c.setLineWidth(0.6)
        self.c.line(MARGIN, 34, WIDTH - MARGIN, 34)
        self.text(MARGIN, 23, self.footer_text, 7.5, color=SOFT, maxw=INNER - 90)
        self.text(WIDTH - MARGIN, 23, self.t["page"].format(x=self.page, y=self.total or self.page), 7.5, color=SOFT, right=True)

    def next_page(self) -> None:
        self.footer()
        self.c.showPage()
        self.page += 1
        self.y = HEIGHT - MARGIN

    def room(self, space: float) -> bool:
        """True si hubo que pasar de pagina."""
        if self.y - space < 48:
            self.next_page()
            return True
        return False

    def letterhead(self, logo: Optional[bytes], company: str, title: str, subtitle: str, right_lines: list[str]) -> None:
        from reportlab.lib.utils import ImageReader

        top, box = self.y, 46
        drawn = False
        if logo:
            try:
                self.c.drawImage(ImageReader(io.BytesIO(logo)), MARGIN, top - box, width=box, height=box, preserveAspectRatio=True, anchor="c", mask="auto")
                drawn = True
            except Exception as exc:
                log.warning("No se pudo dibujar el logo: %s", type(exc).__name__)
        if not drawn:
            self.c.setFillColorRGB(*NAVY)
            self.c.roundRect(MARGIN, top - box, box, box, 7, stroke=0, fill=1)
            self.text(MARGIN + box / 2 - 15, top - box / 2 - 3, self.fit(company.upper(), 7.5, 30, "Helvetica-Bold"), 7.5, bold=True, color=(1, 1, 1))
        x = MARGIN + box + 12
        self.text(x, top - 19, title, 15, bold=True, color=NAVY, maxw=INNER - box - 150)
        self.text(x, top - 35, subtitle, 8.5, color=SOFT, maxw=INNER - box - 150)
        for i, line in enumerate(right_lines):
            self.text(WIDTH - MARGIN, top - 15 - 12 * i, line, 7.5, color=SOFT, right=True, maxw=135)
        self.y = top - box - 8
        self.c.setStrokeColorRGB(*NAVY)
        self.c.setLineWidth(1.6)
        self.c.line(MARGIN, self.y, WIDTH - MARGIN, self.y)
        self.y -= 14

    def tiles(self, items: list[tuple[str, str, Optional[tuple]]]) -> None:
        gap = 8
        w = (INNER - gap * (len(items) - 1)) / len(items)
        for i, (label, value, dot) in enumerate(items):
            x = MARGIN + i * (w + gap)
            self.c.setStrokeColorRGB(*LINE)
            self.c.setLineWidth(0.7)
            self.c.roundRect(x, self.y - 36, w, 38, 5, stroke=1, fill=0)
            tx = x + 8
            if dot:
                self.c.setFillColorRGB(*dot)
                self.c.circle(tx + 3, self.y - 9, 3, stroke=0, fill=1)
                tx += 10
            self.text(tx, self.y - 12, label, 7.8, color=SOFT, maxw=w - (tx - x) - 4)
            self.text(x + 8, self.y - 27, value, 11, bold=True, maxw=w - 14)
        self.y -= 50

    def heading(self, value: str, accent=NAVY) -> None:
        self.room(40)
        self.c.setFillColorRGB(*accent)
        self.c.rect(MARGIN, self.y - 3, 3.5, 13, stroke=0, fill=1)
        self.text(MARGIN + 9, self.y, value, 10.5, bold=True, color=NAVY)
        self.y -= 18

    def table_head(self, labels: list[str], widths: list[float], accent=NAVY) -> None:
        self.c.setFillColorRGB(*accent)
        self.c.rect(MARGIN, self.y - 6, INNER, 17, stroke=0, fill=1)
        x = MARGIN
        for label, w in zip(labels, widths):
            self.text(x + 4, self.y - 1, label.upper(), 7, bold=True, color=(1, 1, 1), maxw=w - 6)
            x += w
        self.y -= 22

    def finish(self) -> bytes:
        self.footer()
        self.c.save()
        return self.buf.getvalue()


def _two_pass(draw: Any) -> bytes:
    """Dibuja una vez para saber cuantas paginas son y otra para escribir "de Y"."""
    return draw(draw(0).page).finish()


