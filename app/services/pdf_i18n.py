TABLES = {"en": EN, "fr": FR}
_TAG = re.compile(r"(<[^>]+>)")
_SEP = re.compile(r"(\s+[·|]\s+)")


def language() -> str:
    lang = company_locale.current_language()
    return lang if lang in TABLES else "es"


def _single(text: str, lang: str) -> str | None:
    table = TABLES[lang]
    if text in table:
        return table[text]
    for pattern, out in PATTERNS[lang]:
        m = pattern.match(text)
        if m:
            return out(m) if callable(out) else m.expand(out)
    # MAYUSCULAS: "TOTAL NÓMINA" -> la traduccion de "Total nómina", en mayusculas.
    if text.isupper() and len(text) > 2:
        key = next((k for k in table if k.upper() == text), None)
        if key is not None:
            return table[key].upper()
    # Etiqueta al inicio: "Fecha: 11/10/2026", "Generado: ...".
    head, sep, rest = text.partition(":")
    if sep and head + ":" in table:
        return table[head + ":"] + rest
    # Etiqueta seguida de un numero o un parentesis: "Mesa 5", "Resumen por empleado (5)".
    for key in sorted((k for k in table if not k.endswith(":")), key=len, reverse=True):
        rest = text[len(key):]
        if text.startswith(key) and re.match(r"^ ?(\(.*\)|\d.*)$", rest):
            inner = rest.strip()
            return table[key] + rest.replace(inner, table.get(inner, inner))
    return None


def _piece(text: str, lang: str) -> str:
    core = text.strip()
    if not core:
        return text
    out = _single(core, lang)
    if out is None and _SEP.search(core):
        parts = _SEP.split(core)
        tr = [p if _SEP.fullmatch(p) else (_single(p.strip(), lang) or p) for p in parts]
        out = "".join(tr) if tr != parts else None
    return text.replace(core, out) if out is not None else text


def tr(text: Any, lang: str | None = None) -> Any:
    """Traduce un texto en espanol al idioma de la empresa; en espanol lo devuelve igual."""
    lang = lang or language()
    if lang == "es" or not isinstance(text, str) or not text.strip():
        return text
    if "<" in text:
        return "".join(p if _TAG.fullmatch(p) else _piece(p, lang) for p in _TAG.split(text))
    return _piece(text, lang)


_INSTALLED = False


def install() -> None:
    """Conecta el diccionario a reportlab (una vez): Canvas.draw*String y Paragraph.
    Con la empresa en espanol cada llamada pasa sin cambios."""
    global _INSTALLED
    if _INSTALLED:
        return
    try:
        from reportlab.pdfgen.canvas import Canvas
        from reportlab.platypus import Paragraph
    except Exception:
        return
    for name in ("drawString", "drawRightString", "drawCentredString"):
        original = getattr(Canvas, name)

        def wrapped(self, x, y, text, *args, __original=original, **kwargs):
            return __original(self, x, y, tr(text), *args, **kwargs)

        setattr(Canvas, name, wrapped)
    paragraph_init = Paragraph.__init__

    def paragraph(self, text, *args, **kwargs):
        return paragraph_init(self, tr(text), *args, **kwargs)

    Paragraph.__init__ = paragraph
    _INSTALLED = True


install()
